def area(p): return sum(p[i][0]*p[(i+1)%len(p)][1]-p[(i+1)%len(p)][0]*p[i][1] for i in range(len(p)))/2
def font(name, polys, adv=640):
    names = ['zero','one','two','three','four','five','six','seven','eight','nine']
    cmap = {ord(str(i)): n for i, n in enumerate(names)}; cmap.update({32:'space',58:'colon',46:'period'})
    order = ['.notdef'] + names + ['space','colon','period']
    fb = FontBuilder(1000, isTTF=True); fb.setupGlyphOrder(order); fb.setupCharacterMap(cmap)
    gl, hm = {}, {}
    for n in order:
        pen = TTGlyphPen(None); ps = polys.get(n, [])
        for p in ps:
            if area(p) > 0: p = p[::-1]
            pen.moveTo(p[0]); [pen.lineTo(q) for q in p[1:]]; pen.closePath()
        gl[n] = pen.glyph(); hm[n] = (adv if n != '.notdef' else 500, int(min([x for p in ps for x, _ in p] or [0])))
    fb.setupGlyf(gl); fb.setupHorizontalMetrics(hm); fb.setupHorizontalHeader(ascent=800, descent=-200)
    fb.setupNameTable({'familyName': name, 'styleName': 'Regular'})
    fb.setupOS2(sTypoAscender=800, sTypoDescender=-200, usWinAscent=800, usWinDescent=200, sCapHeight=700, sxHeight=500)
    fb.setupPost(); b = io.BytesIO(); fb.save(b)
    return "@font-face{font-family:'%s';src:url(data:font/ttf;base64,%s) format('truetype');font-display:block}\n" % (name, base64.b64encode(b.getvalue()).decode())
